import fs from "node:fs/promises";
import {connectPostgres} from "./postgres-client.mjs";

if(!process.env.DATABASE_URL) throw new Error("DATABASE_URL is required");
const db=await connectPostgres();

const {rows:enumRows}=await db.query(`
  select t.typname enum_name,e.enumlabel
  from pg_type t
  join pg_enum e on e.enumtypid=t.oid
  join pg_namespace n on n.oid=t.typnamespace
  where n.nspname='public'
  order by t.typname,e.enumsortorder
`);
const enums=new Map();
for(const row of enumRows){
  if(!enums.has(row.enum_name)) enums.set(row.enum_name,[]);
  enums.get(row.enum_name).push(row.enumlabel);
}

const {rows:columnRows}=await db.query(`
  select c.table_name,c.column_name,c.data_type,c.udt_name,c.is_nullable,
         c.column_default,c.is_identity,c.ordinal_position
  from information_schema.columns c
  join information_schema.tables t
    on t.table_schema=c.table_schema and t.table_name=c.table_name
  where c.table_schema='public' and t.table_type='BASE TABLE'
    and c.table_name <> '_chapli_migrations'
  order by c.table_name,c.ordinal_position
`);
const tables=new Map();
for(const row of columnRows){
  if(!tables.has(row.table_name)) tables.set(row.table_name,[]);
  tables.get(row.table_name).push(row);
}

const {rows:fkRows}=await db.query(`
  select
    tc.table_name,
    kcu.column_name,
    ccu.table_name foreign_table_name,
    ccu.column_name foreign_column_name,
    tc.constraint_name
  from information_schema.table_constraints tc
  join information_schema.key_column_usage kcu
    on tc.constraint_name=kcu.constraint_name and tc.constraint_schema=kcu.constraint_schema
  join information_schema.constraint_column_usage ccu
    on ccu.constraint_name=tc.constraint_name and ccu.constraint_schema=tc.constraint_schema
  where tc.constraint_type='FOREIGN KEY' and tc.table_schema='public'
  order by tc.table_name,tc.constraint_name,kcu.ordinal_position
`);

const {rows:functionRows}=await db.query(`
  select p.proname,pg_get_function_identity_arguments(p.oid) arguments,
         pg_get_function_result(p.oid) result
  from pg_proc p join pg_namespace n on n.oid=p.pronamespace
  where n.nspname='public' and p.prokind='f'
  order by p.proname
`);
const functionNames=[...new Set(functionRows.map(row=>row.proname))];

const scalar=(row)=>{
  const name=row.udt_name;
  if(enums.has(name)) return `Database["public"]["Enums"]["${name}"]`;
  if(name.startsWith("_")){
    const inner=scalar({...row,udt_name:name.slice(1),data_type:"USER-DEFINED"});
    return `${inner}[]`;
  }
  if(["int2","int4","int8","float4","float8","numeric","decimal"].includes(name)) return "number";
  if(["bool"].includes(name)) return "boolean";
  if(["json","jsonb"].includes(name)) return "Json";
  return "string";
};
const fieldType=(row)=>`${scalar(row)}${row.is_nullable==="YES"?" | null":""}`;

let output=`// Generated by scripts/generate-database-types.mjs from the live Supabase schema.\n// Do not edit by hand. Run: npm run db:types\n\nexport type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];\n\nexport type Database = {\n  public: {\n    Tables: {\n`;

for(const [table,columns] of tables){
  const relationships=fkRows.filter(row=>row.table_name===table);
  output+=`      ${JSON.stringify(table)}: {\n        Row: {\n`;
  for(const column of columns) output+=`          ${JSON.stringify(column.column_name)}: ${fieldType(column)};\n`;
  output+=`        };\n        Insert: {\n`;
  for(const column of columns){
    const optional=column.is_nullable==="YES"||column.column_default!==null||column.is_identity==="YES";
    output+=`          ${JSON.stringify(column.column_name)}${optional?"?":""}: ${fieldType(column)};\n`;
  }
  output+=`        };\n        Update: {\n`;
  for(const column of columns) output+=`          ${JSON.stringify(column.column_name)}?: ${fieldType(column)};\n`;
  output+=`        };\n        Relationships: [\n`;
  for(const relation of relationships){
    output+=`          { foreignKeyName: ${JSON.stringify(relation.constraint_name)}; columns: [${JSON.stringify(relation.column_name)}]; isOneToOne: false; referencedRelation: ${JSON.stringify(relation.foreign_table_name)}; referencedColumns: [${JSON.stringify(relation.foreign_column_name)}] },\n`;
  }
  output+=`        ];\n      };\n`;
}

output+=`    };\n    Views: Record<string, never>;\n    Functions: {\n`;
for(const name of functionNames){
  output+=`      ${JSON.stringify(name)}: { Args: Record<string, unknown>; Returns: unknown };\n`;
}
output+=`    };\n    Enums: {\n`;
for(const [name,values] of enums){
  output+=`      ${JSON.stringify(name)}: ${values.map(JSON.stringify).join(" | ")};\n`;
}
output+=`    };\n    CompositeTypes: Record<string, never>;\n  };\n};\n\n`;
output+=`export type Tables<T extends keyof Database["public"]["Tables"]> = Database["public"]["Tables"][T]["Row"];\n`;
output+=`export type TablesInsert<T extends keyof Database["public"]["Tables"]> = Database["public"]["Tables"][T]["Insert"];\n`;
output+=`export type TablesUpdate<T extends keyof Database["public"]["Tables"]> = Database["public"]["Tables"][T]["Update"];\n`;
output+=`export type Enums<T extends keyof Database["public"]["Enums"]> = Database["public"]["Enums"][T];\n`;

await fs.mkdir("src/types",{recursive:true});
await fs.writeFile("src/types/database.generated.ts",output,"utf8");
await db.end();
console.log(JSON.stringify({tables:tables.size,enums:enums.size,functions:functionNames.length,bytes:Buffer.byteLength(output)}));
